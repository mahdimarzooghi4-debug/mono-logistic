import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import App from './App'

describe('courier home', () => {
  it('shows the Figma demo mission and cycles proposal cards', () => {
    render(<App />)
    expect(screen.getByText('MIS-۱۰۵۱۲')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'نمایش پیشنهاد 2' }))
    expect(screen.getByText('MIS-۱۰۵۰۹')).toBeInTheDocument()
  })

  it('moves through pickup and requires package checks before handoff', () => {
    render(<App />)
    const online = screen.getByRole('button', { name: 'آنلاین' })
    fireEvent.click(online)
    expect(screen.getByText('فعلا آفلاین هستید')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'پذیرش این ماموریت' }))
    expect(screen.getByText('MIS-۱۰۴۹۸ • حرکت به مبدا')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'گزارش مشکل' }))
    expect(screen.getByRole('status')).toHaveTextContent('گزارش مشکل برای این مأموریت ثبت شد')
    fireEvent.click(screen.getByRole('button', { name: 'رسیدم به مبدا' }))
    expect(screen.getByText('MIS-۱۰۴۹۸ • رسیدن به مبدا')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'سفارش را تحویل گرفتم' }))
    expect(screen.getByRole('status')).toHaveTextContent('تعداد و سلامت بسته‌ها را بررسی کنید')
    fireEvent.click(screen.getByLabelText('تعداد درست است'))
    fireEvent.click(screen.getByLabelText('بسته سالم است'))
    fireEvent.click(screen.getByRole('button', { name: 'سفارش را تحویل گرفتم' }))
    expect(screen.getByText('MIS-۱۰۴۹۸ • حرکت به مقصد')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'رسیدم به مقصد' }))
    expect(screen.getByText('MIS-۱۰۴۹۸ • رسیدن به مقصد')).toBeInTheDocument()
    expect(screen.getByLabelText('یادداشت تحویل اختیاری')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'تحویل انجام شد' }))
    expect(screen.getByText('MIS-۱۰۴۹۸ • تحویل موفق')).toBeInTheDocument()
    expect(screen.getByText('۵۱۱٬۴۲۰ تومان')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'جزئیات مأموریت' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('HNA-۸۳۹۲۵۱')
    fireEvent.click(screen.getByRole('button', { name: 'بستن جزئیات' }))
    fireEvent.click(screen.getByRole('button', { name: 'ماموریت‌ها' }))
    expect(screen.getByText('فعال و تاریخچه')).toBeInTheDocument()
    expect(screen.getByText('MIS-۱۰۴۹۸')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('tab', { name: 'تکمیل‌شده' }))
    expect(screen.queryByText('MIS-۱۰۵۰۳')).not.toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('جست‌وجوی شناسه یا مقصد'), { target: { value: 'MIS-۱۰۴۹۱' } })
    expect(screen.getByText('MIS-۱۰۴۹۱')).toBeInTheDocument()
    expect(screen.queryByText('MIS-۱۰۴۹۸')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'خانه' }))
    expect(screen.getByRole('heading', { name: 'پیشنهادهای ماموریت' })).toBeInTheDocument()
  })

  it('shows the wallet and records a validated demo withdrawal', () => {
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: 'درآمد' }))
    expect(screen.getByText('درآمد و کیف پول')).toBeInTheDocument()
    expect(screen.getByText('۵۱۱٬۴۲۰ تومان')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'برداشت وجه' }))
    fireEvent.change(screen.getByLabelText('مبلغ برداشت'), { target: { value: '200000' } })
    fireEvent.click(screen.getByRole('button', { name: 'تأیید برداشت نمایشی' }))
    expect(screen.getByText('۳۱۱٬۴۲۰ تومان')).toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('به بک‌اند بانکی متصل نیست')
    expect(screen.getAllByText('−۲۰۰٬۰۰۰ تومان')).toHaveLength(2)
  })
})
